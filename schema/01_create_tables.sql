-- =====================================================================
-- 01_create_tables.sql
-- Smart Bike Rental App - PostgreSQL 14+
-- Source: erdfinal.drawio (19 tables, 32 foreign-key relationships)
--
-- What this file contains
--   * Tables, columns, data types, NOT NULL, DEFAULTs
--   * Primary keys, UNIQUE keys (the "UK" columns in the ERD)
--   * All foreign keys, with ON DELETE rules
--
-- Run order:  01_create_tables.sql  ->  02_constraints_indexes.sql  ->  03_seed_data.sql
--
-- Notes
--   * PKs are identity columns (modern replacement for the ERD's SERIAL).
--   * Timestamps are TIMESTAMPTZ so times are unambiguous across time zones.
--   * ERD "exactly 1" link -> NOT NULL foreign key; "0..1" link -> nullable.
--   * ON DELETE: history (rides, payments, subscriptions) is protected with
--     RESTRICT; optional links keep the row and clear the link (SET NULL);
--     pure child data (docks, notifications, alerts) goes with its parent (CASCADE).
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- ACTORS: riders, admins, companies
-- ---------------------------------------------------------------------
CREATE TABLE riders (
    rider_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    giu_email              VARCHAR(255) NOT NULL,
    password_hash          VARCHAR(255) NOT NULL,
    email_verified         BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_login_attempts  SMALLINT     NOT NULL DEFAULT 0,
    locked_until           TIMESTAMPTZ,                       -- NULL = account not locked
    referral_code          VARCHAR(12)  NOT NULL,
    CONSTRAINT uq_riders_referral_code UNIQUE (referral_code)
);
-- UK on giu_email, case-insensitive: Foo@giu.edu and foo@giu.edu are the same account.
CREATE UNIQUE INDEX uq_riders_giu_email ON riders (lower(giu_email));

CREATE TABLE admins (
    admin_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_email    VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL
);
CREATE UNIQUE INDEX uq_admins_admin_email ON admins (lower(admin_email));

CREATE TABLE companies (
    company_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_email  VARCHAR(255) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL
);
CREATE UNIQUE INDEX uq_companies_company_email ON companies (lower(company_email));

-- ---------------------------------------------------------------------
-- RIDER ONBOARDING & COMMUNICATION
-- ---------------------------------------------------------------------
-- riders submit id_verifications; admins review them
CREATE TABLE id_verifications (
    id_verification_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id              INTEGER      NOT NULL,
    reviewed_by_admin_id  INTEGER,                              -- NULL until an admin reviews
    id_photo_url          VARCHAR(255) NOT NULL,
    verification_status   VARCHAR(15)  NOT NULL DEFAULT 'pending',
    rejection_reason      VARCHAR(255),
    submitted_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_idv_rider FOREIGN KEY (rider_id)
        REFERENCES riders (rider_id) ON DELETE CASCADE,
    CONSTRAINT fk_idv_admin FOREIGN KEY (reviewed_by_admin_id)
        REFERENCES admins (admin_id) ON DELETE SET NULL
);

-- riders / admins receive notifications
CREATE TABLE notifications (
    notification_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id         INTEGER,
    admin_id         INTEGER,
    type             VARCHAR(30)  NOT NULL,
    message          VARCHAR(255) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_notif_rider FOREIGN KEY (rider_id)
        REFERENCES riders (rider_id) ON DELETE CASCADE,
    CONSTRAINT fk_notif_admin FOREIGN KEY (admin_id)
        REFERENCES admins (admin_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- PLANS, SUBSCRIPTIONS, PRICING, DISCOUNTS
-- ---------------------------------------------------------------------
-- companies offer subscription_plans
CREATE TABLE subscription_plans (
    subscription_plan_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            INTEGER       NOT NULL,
    plan_name             VARCHAR(50)   NOT NULL,
    price                 NUMERIC(10,2) NOT NULL,
    duration_days         INTEGER       NOT NULL,
    includes              VARCHAR(255),
    CONSTRAINT uq_plan_name UNIQUE (plan_name),
    CONSTRAINT fk_plan_company FOREIGN KEY (company_id)
        REFERENCES companies (company_id) ON DELETE RESTRICT
);

-- riders hold subscriptions, bought as a subscription_plan
CREATE TABLE subscriptions (
    subscription_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id              INTEGER NOT NULL,
    subscription_plan_id  INTEGER NOT NULL,
    start_date            DATE    NOT NULL,
    expiry_date           DATE    NOT NULL,
    CONSTRAINT fk_sub_rider FOREIGN KEY (rider_id)
        REFERENCES riders (rider_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sub_plan FOREIGN KEY (subscription_plan_id)
        REFERENCES subscription_plans (subscription_plan_id) ON DELETE RESTRICT
);

-- companies set pricing_rules
CREATE TABLE pricing_rules (
    pricing_rule_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            INTEGER      NOT NULL,
    per_minute_rate       NUMERIC(6,2) NOT NULL,
    overtime_rate         NUMERIC(6,2) NOT NULL,
    effective_start_date  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_pr_company FOREIGN KEY (company_id)
        REFERENCES companies (company_id) ON DELETE RESTRICT
);

-- companies define discounts
CREATE TABLE discounts (
    discount_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         INTEGER      NOT NULL,
    discount_type      VARCHAR(15)  NOT NULL,
    percent            NUMERIC(5,2) NOT NULL,
    min_monthly_rides  INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT fk_disc_company FOREIGN KEY (company_id)
        REFERENCES companies (company_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- INFRASTRUCTURE: stations, docks, bikes, alerts, areas
-- ---------------------------------------------------------------------
CREATE TABLE stations (
    station_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_name     VARCHAR(100) NOT NULL,
    station_type     VARCHAR(10)  NOT NULL,
    latitude         NUMERIC(9,6) NOT NULL,
    longitude        NUMERIC(9,6) NOT NULL,
    total_docks      INTEGER      NOT NULL DEFAULT 0,
    docks_available  INTEGER      NOT NULL DEFAULT 0,
    CONSTRAINT uq_station_name UNIQUE (station_name)
);

-- stations contain docks
CREATE TABLE docks (
    dock_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id   INTEGER     NOT NULL,
    dock_status  VARCHAR(10) NOT NULL DEFAULT 'available',
    CONSTRAINT fk_dock_station FOREIGN KEY (station_id)
        REFERENCES stations (station_id) ON DELETE CASCADE
);

-- docks hold bikes
CREATE TABLE bikes (
    bike_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dock_id                INTEGER,                              -- NULL while the bike is out on a ride
    qr_code                VARCHAR(100) NOT NULL,
    bike_status            VARCHAR(15)  NOT NULL DEFAULT 'available',
    latitude               NUMERIC(9,6),
    longitude              NUMERIC(9,6),
    last_location_at       TIMESTAMPTZ,
    next_maintenance_date  DATE,
    CONSTRAINT uq_bike_qr UNIQUE (qr_code),
    CONSTRAINT fk_bike_dock FOREIGN KEY (dock_id)
        REFERENCES docks (dock_id) ON DELETE SET NULL
);

-- stations trigger station_alerts
CREATE TABLE station_alerts (
    station_alert_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id        INTEGER     NOT NULL,
    bike_count        INTEGER     NOT NULL,
    alert_status      VARCHAR(10) NOT NULL DEFAULT 'open',
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ,
    CONSTRAINT fk_alert_station FOREIGN KEY (station_id)
        REFERENCES stations (station_id) ON DELETE CASCADE
);

-- admins draw areas
CREATE TABLE areas (
    area_id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id              INTEGER    NOT NULL,
    area_type             VARCHAR(5) NOT NULL,
    boundary              JSONB      NOT NULL,                   -- e.g. a GeoJSON polygon
    block_duration_hours  INTEGER,
    CONSTRAINT fk_area_admin FOREIGN KEY (admin_id)
        REFERENCES admins (admin_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- RIDES
-- ---------------------------------------------------------------------
-- riders ride bikes; a session starts at one station and ends at another
CREATE TABLE sessions (
    session_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id          INTEGER     NOT NULL,
    bike_id           INTEGER     NOT NULL,
    start_station_id  INTEGER     NOT NULL,
    end_station_id    INTEGER,                                   -- NULL until the bike is returned
    pricing_rule_id   INTEGER     NOT NULL,
    subscription_id   INTEGER,                                   -- NULL for pay-per-ride
    start_time        TIMESTAMPTZ NOT NULL DEFAULT now(),
    end_time          TIMESTAMPTZ,
    free_minutes      INTEGER     NOT NULL DEFAULT 0,
    session_status    VARCHAR(10) NOT NULL DEFAULT 'active',
    CONSTRAINT fk_sess_rider   FOREIGN KEY (rider_id)         REFERENCES riders (rider_id)               ON DELETE RESTRICT,
    CONSTRAINT fk_sess_bike    FOREIGN KEY (bike_id)          REFERENCES bikes (bike_id)                 ON DELETE RESTRICT,
    CONSTRAINT fk_sess_start   FOREIGN KEY (start_station_id) REFERENCES stations (station_id)           ON DELETE RESTRICT,
    CONSTRAINT fk_sess_end     FOREIGN KEY (end_station_id)   REFERENCES stations (station_id)           ON DELETE RESTRICT,
    CONSTRAINT fk_sess_pricing FOREIGN KEY (pricing_rule_id)  REFERENCES pricing_rules (pricing_rule_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sess_sub     FOREIGN KEY (subscription_id)  REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- PAYMENTS
-- ---------------------------------------------------------------------
-- a payment covers a session OR a subscription, and may apply one discount
CREATE TABLE payments (
    payment_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        INTEGER,
    subscription_id   INTEGER,
    discount_id       INTEGER,
    receipt_number    VARCHAR(20),                               -- issued once the payment succeeds
    amount            NUMERIC(10,2) NOT NULL,                    -- final amount after any discount
    payment_method    VARCHAR(10)   NOT NULL,
    payment_status    VARCHAR(10)   NOT NULL DEFAULT 'pending',
    failure_reason    VARCHAR(255),
    CONSTRAINT uq_payment_receipt UNIQUE (receipt_number),
    CONSTRAINT fk_pay_session  FOREIGN KEY (session_id)      REFERENCES sessions (session_id)           ON DELETE RESTRICT,
    CONSTRAINT fk_pay_sub      FOREIGN KEY (subscription_id) REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pay_discount FOREIGN KEY (discount_id)     REFERENCES discounts (discount_id)         ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- BLOCKS, COMPLAINTS, MAINTENANCE
-- ---------------------------------------------------------------------
-- riders get blocks (optionally because of a session and/or an area)
CREATE TABLE blocks (
    block_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id    INTEGER      NOT NULL,
    session_id  INTEGER,
    area_id     INTEGER,
    reason      VARCHAR(255) NOT NULL,
    starts_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    ends_at     TIMESTAMPTZ,                                     -- NULL = until lifted manually
    CONSTRAINT fk_block_rider   FOREIGN KEY (rider_id)   REFERENCES riders (rider_id)     ON DELETE RESTRICT,
    CONSTRAINT fk_block_session FOREIGN KEY (session_id) REFERENCES sessions (session_id) ON DELETE SET NULL,
    CONSTRAINT fk_block_area    FOREIGN KEY (area_id)    REFERENCES areas (area_id)       ON DELETE SET NULL
);

-- riders post complaints about a bike / station / session
CREATE TABLE complaints (
    complaint_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rider_id          INTEGER      NOT NULL,
    bike_id           INTEGER,
    station_id        INTEGER,
    session_id        INTEGER,
    reference_number  VARCHAR(20)  NOT NULL,
    description       TEXT         NOT NULL,
    photo_url         VARCHAR(255),
    status            VARCHAR(15)  NOT NULL DEFAULT 'open',
    time_stamp        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    closed_at         TIMESTAMPTZ,
    CONSTRAINT uq_complaint_reference UNIQUE (reference_number),
    CONSTRAINT fk_comp_rider   FOREIGN KEY (rider_id)   REFERENCES riders (rider_id)     ON DELETE RESTRICT,
    CONSTRAINT fk_comp_bike    FOREIGN KEY (bike_id)    REFERENCES bikes (bike_id)       ON DELETE SET NULL,
    CONSTRAINT fk_comp_station FOREIGN KEY (station_id) REFERENCES stations (station_id) ON DELETE SET NULL,
    CONSTRAINT fk_comp_session FOREIGN KEY (session_id) REFERENCES sessions (session_id) ON DELETE SET NULL
);

-- admins schedule maintenance_tasks for bikes (optionally created from a complaint)
-- technician_id / technician_name are plain attributes in the ERD (no technicians table).
CREATE TABLE maintenance_tasks (
    maintenance_task_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bike_id              INTEGER      NOT NULL,
    complaint_id         INTEGER,                                -- NULL for routine maintenance
    admin_id             INTEGER      NOT NULL,                  -- admin who scheduled the task
    technician_id        INTEGER,                                -- NULL until assigned
    technician_name      VARCHAR(100),
    scheduled_date       DATE         NOT NULL,
    task_status          VARCHAR(15)  NOT NULL DEFAULT 'scheduled',
    CONSTRAINT fk_mt_bike      FOREIGN KEY (bike_id)      REFERENCES bikes (bike_id)           ON DELETE RESTRICT,
    CONSTRAINT fk_mt_complaint FOREIGN KEY (complaint_id) REFERENCES complaints (complaint_id) ON DELETE SET NULL,
    CONSTRAINT fk_mt_admin     FOREIGN KEY (admin_id)     REFERENCES admins (admin_id)         ON DELETE RESTRICT
);

COMMIT;
